from importlib import resources as impresources
import numpy as np
from pathlib import Path
from pydrake.all import (
    RigidTransform,
    RollPitchYaw,
    Simulator,
)
from typing import List

# Internal Imports
from brom_drake.all import drakeify_my_urdf, GripperType, MeshReplacementStrategy
from brom_drake import robots
from brom_drake.productions.grasping.config import (
    Configuration as GraspSelection1Configuration,
)
from brom_drake.productions.grasping.grasp_selection import GraspSelection1
from brom_drake.productions.grasping.object_description import ObjectDescription


def side_grasp_selection_algorithm(
    object_description: ObjectDescription,
) -> List[RigidTransform]:
    """
    *Description*

    A simple grasp selection algorithm that returns a trajectory for the
    gripper's base frame (with respect to the object) which:
    - starts at a pre-grasp pose that is "backed off" from the object,
    - moves to an intermediate pose closer to the object, and
    - ends at the grasp pose.

    A real grasp selection algorithm would inspect ``object_description.geometry``
    (e.g., its collision shapes) to choose the grasp. This one always returns
    the same poses, which were chosen for the 500ml Erlenmeyer flask.

    *Parameters*

    object_description: ObjectDescription
        The path to the model of the object being grasped and the object's geometry.

    *Returns*

    X_ObjectGripper_trajectory: List[RigidTransform]
        The waypoints of the gripper's base frame with respect to the object.
        The last waypoint is the grasp pose.
    """
    n_shapes = len(object_description.geometry.collision_shapes)
    print(
        f"Selecting a grasp for the object at {object_description.path_to_object} "
        + f"({n_shapes} collision shapes)"
    )

    # The Grasp Pose (i.e. the target pose of the gripper wrist when grasping the object)
    X_ObjectGrasp = RigidTransform(
        p=np.array([-0.08, 0.05, 0.15]),
        rpy=RollPitchYaw(0.1, (14.0 / 20.0) * np.pi, 0.1),
    )

    # The Pre-Grasp Pose and an intermediate pose, both "backed off" from the
    # grasp pose along the gripper's approach (z) axis
    X_ObjectPreGrasp = X_ObjectGrasp.multiply(
        RigidTransform(p=np.array([0.0, 0.0, -0.2]))
    )
    X_ObjectIntermediate = X_ObjectGrasp.multiply(
        RigidTransform(p=np.array([0.0, 0.0, -0.05]))
    )

    return [X_ObjectPreGrasp, X_ObjectIntermediate, X_ObjectGrasp]


def main():
    """
    *Description*

    In this example, we will demonstrate how to:
    - Load a model into the `GraspSelection1` production
    - Provide a grasp selection algorithm (i.e., a function that takes the path to
      the object and returns the trajectory of the gripper wrist)
    - Run a simulation of the grasp attempt, visualizing the results in Meshcat.

    The trajectory generated by the algorithm is recorded in the production's
    build metadata (in the `brom` directory).
    """

    # Setup

    # Create erlenmeyer flask urdf
    erlenmeyer_flask_file = str(
        impresources.files(robots) / "models/erlenmeyer_flask/500ml.urdf"
    )

    drakeified_flask_urdf = Path("brom/models/500ml/500ml.drake.urdf")
    if not drakeified_flask_urdf.exists():
        drakeified_flask_urdf = drakeify_my_urdf(
            erlenmeyer_flask_file,
            overwrite_old_logs=True,
            log_file_name="GraspSelection1Example_AddManipulandToPlant_flask.log",
            # For you (yes, you!): Comment out the line below, to see what the default collision mesh looks like
            collision_mesh_replacement_strategy=MeshReplacementStrategy.kWithConvexDecomposition,
        )

    # Create the production
    production = GraspSelection1(
        path_to_object=str(drakeified_flask_urdf),
        gripper_choice=GripperType.Robotiq_2f_85,
        grasp_gripper_command=np.array([0.7]),
        meshcat_port_number=7001,  # Use None for CI
        config=GraspSelection1Configuration(),
    )

    # Use the grasp selection algorithm to define the gripper's trajectory and build the production.
    # Build with watcher (so we can view the simulation's data in `brom/watcher/plots` which is helpful for debugging)
    diagram, diagram_context = production.easy_cast_and_build(
        side_grasp_selection_algorithm,
        with_watcher=True,
    )

    # Set up simulation
    script = production.config.script

    simulator = Simulator(diagram, diagram_context)
    simulator.set_target_realtime_rate(1.0)
    simulator.Initialize()
    simulator.AdvanceTo(script.total_time())


if __name__ == "__main__":
    main()
